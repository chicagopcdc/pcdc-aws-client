import pytest
from unittest.mock import patch, MagicMock
from pcdc_aws_client.errors import InternalError
from botocore.exceptions import ClientError


def test_config_sets_client(boto_manager):
    bm, _ = boto_manager
    with patch("pcdc_aws_client.boto.client") as mock_client:
            new_client = MagicMock()
            mock_client.return_value = new_client
            config = {"aws_access_key_id": "AKDAW", "aws_secret_access_key": "ssdfsl"}
            bm.send_email("a@example.com", "b@example.com", "Hi", "<p>hi</p>", config=config)
            mock_client.assert_called_once_with("ses", **config)
            new_client.send_email.assert_called_once()

def make_client_error(message="Message rejected"):
    return ClientError(
        error_response={"Error": {"Code": "MessageRejected", "Message": message}},
        operation_name="SendEmail",
    )


def test_recipient_string_is_wrapped_in_list(boto_manager):
    bm, _ = boto_manager
    ses_client = bm.ses_client
    ses_client.send_email.return_value = {"MessageId": "abc123"}

    bm.send_email(
        SENDER="a@example.com",
        RECIPIENT="b@example.com",
        SUBJECT="Hi",
        BODY_HTML="<p>hello</p>",
    )

    _, kwargs = ses_client.send_email.call_args
    assert kwargs["Destination"]["ToAddresses"] == ["b@example.com"]


def test_recipient_list_is_passed_through_unchanged(boto_manager):
    bm, _ = boto_manager
    ses_client = bm.ses_client
    ses_client.send_email.return_value = {"MessageId": "abc123"}

    recipients = ["b@example.com", "c@example.com"]
    bm.send_email(
        SENDER="a@example.com", RECIPIENT=recipients, SUBJECT="Hi", BODY_HTML="<p>hi</p>"
    )

    _, kwargs = ses_client.send_email.call_args
    assert kwargs["Destination"]["ToAddresses"] == recipients
    assert kwargs["Destination"]["ToAddresses"] is recipients  # not copied/rebuilt


