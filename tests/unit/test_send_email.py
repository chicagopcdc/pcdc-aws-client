def test_body_text_autogenerated_when_not_provided(boto_manager):
    bm, _ = boto_manager
    ses_client = bm.ses_client
    ses_client.send_email.return_value = {"MessageId": "abc123"}

    with patch("pcdc_aws_client.boto.html2text") as mock_html2text:
        mock_html2text.html2text.return_value = "hello (plain text)"

        bm.send_email(
            SENDER="a@example.com", RECIPIENT="b@example.com", SUBJECT="Hi",
            BODY_HTML="<p>hello</p>",
        )

        mock_html2text.html2text.assert_called_once_with("<p>hello</p>")

    _, kwargs = ses_client.send_email.call_args
    assert kwargs["Message"]["Body"]["Text"]["Data"] == "hello (plain text)"


def test_body_text_not_overwritten_when_explicitly_provided(boto_manager):
    bm, _ = boto_manager
    ses_client = bm.ses_client
    ses_client.send_email.return_value = {"MessageId": "abc123"}

    with patch("pcdc_aws_client.boto.html2text") as mock_html2text:
        bm.send_email(
            SENDER="a@example.com", RECIPIENT="b@example.com", SUBJECT="Hi",
            BODY_HTML="<p>hello</p>", BODY_TEXT="plain hello",
        )

        mock_html2text.html2text.assert_not_called()

    _, kwargs = ses_client.send_email.call_args
    assert kwargs["Message"]["Body"]["Text"]["Data"] == "plain hello"


def test_message_structure_sent_to_ses(boto_manager):
    bm, _ = boto_manager
    ses_client = bm.ses_client
    ses_client.send_email.return_value = {"MessageId": "abc123"}

    bm.send_email(
        SENDER="a@example.com", RECIPIENT="b@example.com", SUBJECT="Test Subject",
        BODY_HTML="<p>hello</p>", BODY_TEXT="hello",
    )

    _, kwargs = ses_client.send_email.call_args
    assert kwargs["Source"] == "a@example.com"
    assert kwargs["Message"]["Subject"]["Data"] == "Test Subject"
    assert kwargs["Message"]["Body"]["Html"]["Data"] == "<p>hello</p>"
    assert kwargs["Message"]["Body"]["Html"]["Charset"] == "UTF-8"

def test_client_error_raises_internal_error(boto_manager):
    bm, _ = boto_manager
    ses_client = bm.ses_client
    ses_client.send_email.side_effect = make_client_error("Email address not verified")

    with pytest.raises(InternalError, match="Email address not verified"):
        bm.send_email(
            SENDER="a@example.com", RECIPIENT="b@example.com", SUBJECT="Hi",
            BODY_HTML="<p>hi</p>",
        )


